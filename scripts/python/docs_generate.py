#!/usr/bin/env python3
"""Generate and validate committed documentation artifacts.

The repository has no remote documentation service. Generated contract pages
and documentation checks therefore run locally (and in local CI); the generated
files are committed explicitly.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = ROOT / "tools" / "ApiInventoryTool" / "shell-api-baseline.json"
GENERATED = ROOT / "docs" / "generated" / "contract-api.en.md"
GENERATED_HEADER = (
    "<!-- Generated by scripts/python/docs_generate.py; do not edit manually. -->"
)
LINK_RE = re.compile(r"\[[^\]]*\]\(([^)]+)\)")
TYPE_RE = re.compile(r"Origo\.[A-Za-z0-9_.+`]+(?:<[^>]+>)?")
REPO_BLOB_RE = re.compile(
    r"https://github\.com/51193/origo/(?:blob|tree)/main/([^#?)]+)"
)


def format_declaration(text: str) -> str:
    text = text.strip().rstrip(":").strip()
    replacements = (
        ("public sealed Class ", "public sealed class "),
        ("public static Class ", "public static class "),
        ("public abstract Class ", "public abstract class "),
        ("public Class ", "public class "),
        ("public static Interface ", "public static interface "),
        ("public Interface ", "public interface "),
        ("public readonly Struct ", "public readonly struct "),
        ("public Struct ", "public struct "),
        ("public sealed Record ", "public sealed record "),
        ("public Record ", "public record "),
        ("public Enum ", "public enum "),
    )
    for old, new in replacements:
        if text.startswith(old):
            return new + text[len(old):]
    return text


def format_member(text: str, owner: str) -> str:
    prefix = owner + "."
    body = text[len(prefix):] if text.startswith(prefix) else text
    if "<Clone>$" in body:
        return ""
    accessor = re.search(
        r" (get|set|init):(public|protected|internal|private)"
        r"(?: (get|set|init):(public|protected|internal|private))?$",
        body,
    )
    if accessor:
        head = body[: accessor.start()].strip()
        parts = [part for part in accessor.groups() if part]
        rendered = []
        for index in range(0, len(parts), 2):
            kind, level = parts[index], parts[index + 1]
            # A single non-public accessor is expressed by the property's own
            # accessibility (e.g. `protected abstract string Key { get; }`);
            # repeating the modifier on the accessor is invalid C# for those
            # protected getters.
            if len(parts) == 2 and level != "public":
                rendered.append(kind)
            else:
                rendered.append(kind if level == "public" else f"{level} {kind}")
        return f"{head} {{ " + " ".join(f"{item};" for item in rendered) + " }"
    return body.replace("; where ", " where ")


def render_contract_api() -> str:
    data = json.loads(BASELINE.read_text(encoding="utf-8"))
    lines = [
        GENERATED_HEADER,
        "",
        "# Generated shell contract API",
        "",
        "This page is generated from `tools/ApiInventoryTool/shell-api-baseline.json`,",
        "the same Roslyn inventory used by the shell API gate. It is the canonical",
        "signature reference for the public shell surface. The inventory records",
        "canonical names, modifiers, and signatures; it is not a compilable source",
        "file. Do not edit it by hand.",
        "",
        "Regenerate and validate locally with:",
        "",
        "```bash",
        "bash scripts/bash/docs.sh generate",
        "bash scripts/bash/docs.sh check",
        "```",
        "",
    ]
    for assembly in data.get("assemblies", []):
        name = assembly.get("name", "")
        entries = list(assembly.get("api", []))
        types: list[str] = []
        for entry in entries:
            if entry.startswith("T:"):
                match = TYPE_RE.search(entry)
                if match:
                    types.append(match.group(0))
        types = sorted(set(types), key=str.casefold)
        members_by_type: dict[str, list[str]] = {type_name: [] for type_name in types}
        unmatched: list[str] = []
        for entry in entries:
            if entry.startswith("T:"):
                continue
            body = entry.split(":", 1)[-1]
            if "<Clone>$" in body:
                # Compiler-generated record clone methods are not part of the
                # documented consumer surface.
                continue
            matches = [type_name for type_name in types if body.startswith(type_name + ".")]
            if not matches:
                unmatched.append(entry)
                continue
            owner = max(matches, key=len)
            members_by_type[owner].append(body)
        if unmatched:
            raise ValueError(
                "baseline entries could not be attributed to a type: "
                + ", ".join(unmatched)
            )
        lines.extend([f"## {name}", ""])
        for type_name in types:
            declaration = next(
                (
                    entry.split(":", 1)[-1]
                    for entry in entries
                    if entry.startswith("T:") and TYPE_RE.search(entry) and TYPE_RE.search(entry).group(0) == type_name
                ),
                type_name,
            )
            lines.extend(
                [f"### `{type_name}`", "", "```csharp", format_declaration(declaration)]
            )
            lines.extend(
                sorted(
                    (
                        formatted
                        for member in members_by_type[type_name]
                        if (formatted := format_member(member, type_name))
                    ),
                    key=str.casefold,
                )
            )
            lines.extend(["```", ""])
    return "\n".join(lines).rstrip() + "\n"


GENERATED_ARTIFACTS = {GENERATED: render_contract_api}


def strip_code_fences(text: str) -> str:
    lines = text.splitlines()
    result = []
    in_fence = False
    for line in lines:
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            result.append("")
            continue
        result.append("" if in_fence else line)
    return "\n".join(result)


def validate_links() -> list[str]:
    errors: list[str] = []
    markdown_files = sorted(ROOT.glob("*.md"))
    markdown_files.extend(sorted((ROOT / "docs").rglob("*.md")))
    for path in markdown_files:
        if not path.is_file():
            continue
        text = strip_code_fences(path.read_text(encoding="utf-8"))
        for raw_target in LINK_RE.findall(text):
            if raw_target.startswith(("http://", "https://")):
                repo_match = REPO_BLOB_RE.match(raw_target)
                if not repo_match:
                    continue
                target = repo_match.group(1)
                if not (ROOT / target).exists():
                    errors.append(
                        f"{path.relative_to(ROOT)}: repository link target missing "
                        f"{raw_target}"
                    )
                continue
            if raw_target.startswith(("mailto:", "#")):
                continue
            target = raw_target.split("#", 1)[0].split("?", 1)[0]
            if not target:
                continue
            if "Xxx" in target or target == "path":
                # The manual-maintenance templates intentionally use placeholders.
                continue
            resolved = (path.parent / target).resolve()
            if not resolved.exists():
                errors.append(f"{path.relative_to(ROOT)}: missing link target {raw_target}")
    return errors


def validate_counts() -> list[str]:
    """Validate the few exact counts that are contractual or table-backed."""
    errors: list[str] = []
    integration_doc = ROOT / "docs" / "Origo.GodotAdapter.Integration.Tests" / "README.en.md"
    runner = ROOT / "Origo.GodotAdapter.Integration.Tests" / "Runner" / "IntegrationTestRunner.cs"
    if not integration_doc.is_file() or not runner.is_file():
        errors.append(
            "integration inventory validation is missing its document or runner source"
        )
    else:
        match = re.search(r"_minimumTestCount\s*=\s*(\d+)", runner.read_text(encoding="utf-8"))
        if not match:
            errors.append("could not read _minimumTestCount from IntegrationTestRunner.cs")
        else:
            floor = int(match.group(1))
            total = 0
            in_table = False
            for line in integration_doc.read_text(encoding="utf-8").splitlines():
                if line.startswith("| Test Class |") and "Tests" in line:
                    in_table = True
                    continue
                if in_table and line.startswith("|"):
                    cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
                    if len(cells) >= 3 and cells[2].isdigit():
                        total += int(cells[2])
                    continue
                if in_table:
                    break
            if total != floor:
                errors.append(
                    "integration test inventory table does not match the runner floor "
                    f"({total} rows vs {floor}); update the table or runner"
                )

    assembly = ROOT / "Origo.GodotAdapter" / "AssemblyAttributes.cs"
    serialization_doc = ROOT / "docs" / "Origo.GodotAdapter" / "Serialization" / "README.en.md"
    if not assembly.is_file() or not serialization_doc.is_file():
        errors.append(
            "Godot type inventory validation is missing its assembly or documentation source"
        )
    else:
        registered = set(re.findall(r"typeof\(([A-Za-z0-9_]+)\)", assembly.read_text(encoding="utf-8")))
        doc_text = serialization_doc.read_text(encoding="utf-8")
        missing = sorted(name for name in registered if f"`{name}`" not in doc_text)
        if missing:
            errors.append(
                "Godot serialization documentation is missing registered types: "
                + ", ".join(missing)
            )
    return errors


SUMMARY_DOCS = [
    ROOT / "README.md",
    ROOT / "docs" / "README.en.md",
    ROOT / "docs" / "usage" / "README.en.md",
    ROOT / "docs" / "usage" / "capabilities.en.md",
    ROOT / "docs" / "usage" / "agent-reference.en.md",
    ROOT / "docs" / "architecture" / "overview.en.md",
    ROOT / "docs" / "Origo.Core" / "README.en.md",
    ROOT / "docs" / "Origo.Core.Contracts" / "README.en.md",
    ROOT / "docs" / "Origo.Core.Kernel" / "README.en.md",
    ROOT / "docs" / "Origo.GodotAdapter" / "README.en.md",
    ROOT / "docs" / "Origo.ConsoleBridge" / "README.en.md",
    ROOT / "docs" / "Origo.SourceGeneration" / "README.en.md",
]
BANNED_SUMMARY_PATTERNS = (
    r"\b\d+ (?:built-in|companion|lifecycle|Godot types|\.cs files|tests)\b",
    r"\b\d+ minutes?\b",
)


def validate_summary_content() -> list[str]:
    errors: list[str] = []
    for path in SUMMARY_DOCS:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        if "quick-start" in text.lower() or "quick start" in text.lower():
            errors.append(f"{path.relative_to(ROOT)}: stale quick-start reference")
        for pattern in BANNED_SUMMARY_PATTERNS:
            match = re.search(pattern, text)
            if match:
                errors.append(
                    f"{path.relative_to(ROOT)}: avoid brittle count '{match.group(0)}'; "
                    "use names or a generated/validated inventory"
                )
    return errors


def validate_generated_registry() -> list[str]:
    errors: list[str] = []
    generated_dir = GENERATED.parent
    if generated_dir.is_dir():
        registered = {path.resolve() for path in GENERATED_ARTIFACTS}
        for path in sorted(generated_dir.glob("*.md")):
            if path.name == "README.en.md":
                continue
            if path.resolve() not in registered:
                try:
                    label = path.relative_to(ROOT)
                except ValueError:
                    label = path
                errors.append(
                    f"{label}: generated artifact is not registered "
                    "in GENERATED_ARTIFACTS"
                )
    return errors


def check_staged_generated() -> list[str]:
    """Ensure every generated artifact staged in the index matches its renderer.

    The working tree check is the normal gate; this catches the common
    pre-commit case where the worktree is regenerated but an older generated
    file was staged.
    """
    errors: list[str] = []
    for path, render in GENERATED_ARTIFACTS.items():
        try:
            staged = subprocess.run(
                ["git", "show", f":{display_path(path)}"],
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
            )
        except OSError as exc:
            errors.append(f"could not read staged generated file: {exc}")
            continue
        if staged.returncode != 0:
            errors.append(
                f"generated file is not staged or tracked: {display_path(path)}; "
                "generate and stage it before commit"
            )
            continue
        if staged.stdout != render():
            errors.append(
                f"staged generated file is stale: {path.relative_to(ROOT)}; "
                "regenerate and stage it before commit"
            )
    return errors


def display_path(path: Path) -> Path:
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def check_generated() -> list[str]:
    errors: list[str] = []
    for path, render in GENERATED_ARTIFACTS.items():
        if not path.is_file():
            errors.append(f"missing generated file: {display_path(path)}")
            continue
        if path.read_text(encoding="utf-8") != render():
            errors.append(
                f"generated file is stale: {display_path(path)}; "
                "run `scripts/bash/docs.sh generate` and commit the result"
            )
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("generate", "check", "check-staged"))
    args = parser.parse_args(argv)
    if args.mode == "generate":
        for path, render in GENERATED_ARTIFACTS.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(render(), encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    if args.mode == "check-staged":
        errors = check_staged_generated()
    else:
        errors = check_generated()
        errors.extend(validate_generated_registry())
        errors.extend(validate_links())
        errors.extend(validate_counts())
        errors.extend(validate_summary_content())
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print("Documentation generated content and links: OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
